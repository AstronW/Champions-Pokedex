package dev.champions.dex

import org.mozilla.javascript.Context
import org.mozilla.javascript.Function
import org.mozilla.javascript.Scriptable
import org.mozilla.javascript.ScriptableObject

/** An isolated, serialized interpreter. Call from a worker dispatcher, never the UI thread. */
class CalculatorEngine(private val readAsset: (String) -> String) {
    @Volatile private var scope: Scriptable? = null

    private fun global(context: Context): Scriptable = scope ?: context.initSafeStandardObjects().also { safe ->
        // Interpreting the ~900 KB engine dominates the cost (seconds); a single calculation afterwards takes tens of ms.
        context.evaluateString(safe, readAsset("calculator/engine.js"), "engine.js", 1, null)
        context.evaluateString(safe, readAsset("calculator/adapter.js"), "adapter.js", 1, null)
        val api = ScriptableObject.getProperty(safe, "dexCalc") as Scriptable
        val init = ScriptableObject.getProperty(api, "init") as Function
        init.call(context, safe, api, arrayOf(readAsset("dex.json"), readAsset("calculator/catalog.json")))
        scope = safe
    }

    private inline fun <T> withContext(block: (Context) -> T): T {
        val context = Context.enter()
        try {
            context.optimizationLevel = -1 // Android cannot load JVM bytecode generated by Rhino.
            context.languageVersion = Context.VERSION_ES6
            context.setClassShutter { false }
            return block(context)
        } finally {
            Context.exit()
        }
    }

    val ready get() = scope != null

    /** Loads the engine ahead of the first calculation. */
    @Synchronized
    fun warmUp() { withContext { global(it) } }

    @Synchronized
    fun calculate(request: String): String = withContext { context ->
            val global = global(context)
            val api = ScriptableObject.getProperty(global, "dexCalc") as Scriptable
            val function = ScriptableObject.getProperty(api, "calculate") as Function
            Context.toString(function.call(context, global, api, arrayOf(request)))
    }
}
