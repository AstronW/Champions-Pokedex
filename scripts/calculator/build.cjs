// Bundle the checked-in upstream source without modifying the adjacent repository.
const fs = require('fs');
const path = require('path');
const vm = require('vm');
const crypto = require('crypto');
const ts = require('typescript');
const root = path.resolve(__dirname, '../..');
const src = path.join(root, 'vendor/damage-calc/src');
const out = path.join(root, 'app/src/main/assets/calculator');
const modules = new Map();
function collect(id) {
  if (modules.has(id)) return;
  const source = fs.readFileSync(path.join(src, id + '.ts'), 'utf8');
  const js = ts.transpileModule(source, {compilerOptions: {
    target: ts.ScriptTarget.ES5, module: ts.ModuleKind.CommonJS,
    downlevelIteration: true, removeComments: true,
  }}).outputText;
  modules.set(id, js);
  for (const [, dep] of js.matchAll(/require\("([^"]+)"\)/g)) {
    let next = path.posix.normalize(path.posix.join(path.posix.dirname(id), dep));
    if (!fs.existsSync(path.join(src, next + '.ts'))) next += '/index';
    collect(next);
  }
}
collect('index');
const bundle = `// MIT: Honko and contributors; see LICENSE-damage-calc.txt. Generated by build.cjs.
var calc = (function() {
if (!Object.fromEntries) Object.fromEntries = function(entries) { var o={}; entries.forEach(function(e){o[e[0]]=e[1];}); return o; };
var modules = {${[...modules].map(([id, js]) => `${JSON.stringify(id)}:function(require,module,exports){\n${js}\n}`).join(',\n')}};
var cache = {};
function load(id) {
  if(cache[id]) return cache[id].exports;
  var module = cache[id] = {exports:{}};
  modules[id](function(dep) {
    var parts=id.split('/'); parts.pop();
    dep.split('/').forEach(function(p){if(p==='..') parts.pop(); else if(p!=='.') parts.push(p);});
    var next=parts.join('/'); if(!modules[next]) next+='/index'; return load(next);
  },module,module.exports);
  return module.exports;
}
return load('index');
})();\n`;
fs.mkdirSync(out, {recursive:true});
fs.writeFileSync(path.join(out, 'engine.js'), bundle);
fs.copyFileSync(path.join(__dirname,'adapter.js'),path.join(out,'adapter.js'));
const context = vm.createContext({}); vm.runInContext(bundle, context);
const calc = context.calc, gen = calc.Generations.get(0);
const dex = JSON.parse(fs.readFileSync(path.join(root, 'app/src/main/assets/dex.json')));
const itemSource = JSON.parse(require('child_process').execFileSync('python', [path.join(__dirname,'import-items.py')], {encoding:'utf8'}));
const species = Array.from(gen.species);
console.log('Champions engine:', species.length, 'species,', Array.from(gen.moves).length, 'moves');
const aliasesPath = path.join(__dirname, 'form-aliases.json');
const aliases = fs.existsSync(aliasesPath) ? JSON.parse(fs.readFileSync(aliasesPath)) : {};
function speciesName(p) {
  const f=p.formEnglish;
  let name=aliases[p.id] || p.english;
  if(!aliases[p.id] && f) {
    if(f.startsWith('Mega ')) name=p.english+'-Mega'+f.slice(('Mega '+p.english).length).replace(/ /g,'-');
    else if(f==='Alolan Form') name+='-Alola';
    else if(f==='Galarian Form') name+='-Galar';
    else if(f==='Hisuian Form') name+='-Hisui';
    else return null;
  }
  return gen.species.get(calc.toID(name))?.name || null;
}
const mapping = Object.fromEntries(dex.pokemon.map(p=>[p.id,speciesName(p)]));
const missing=dex.pokemon.filter(p=>!mapping[p.id]);
fs.writeFileSync(path.join(out,'catalog.json'),JSON.stringify({species:mapping,
  moves:Object.fromEntries(dex.moves.filter(m=>m.available).map(m=>[m.id,gen.moves.get(calc.toID(m.english))?.name || (m.id===1 ? 'Pound' : null)])),
  moveHits:Object.fromEntries(dex.moves.filter(m=>m.available).map(m=>{
    const data=gen.moves.get(calc.toID(m.english));
    const hits=data?.multihit;
    return [m.id,Array.isArray(hits)?hits:(typeof hits==='number'?[data.multiaccuracy?1:hits,hits]:[1,1])];
  })),
  abilities:Object.fromEntries(dex.abilities.map(a=>[a.id,gen.abilities.get(calc.toID(a.english))?.name || null])),
  items:Array.from(gen.items).map(i=>({name:i.name,label:itemSource.names[i.name] || i.name})), natures:Array.from(gen.natures).map(n=>({name:n.name,plus:n.plus,minus:n.minus})),
},null,2)+'\n');
const sha = f=>crypto.createHash('sha256').update(fs.readFileSync(f)).digest('hex');
fs.writeFileSync(path.join(out,'provenance.json'),JSON.stringify({
  repository:'https://github.com/smogon/damage-calc',commit:'eb9af6d94e7ee0ce034d2d6f2d44d4b2d66ff981',generation:0,
  dexSha256:sha(path.join(root,'app/src/main/assets/dex.json')),
  itemSourceSha256:itemSource.sha256,
  engineSha256:sha(path.join(out,'engine.js')),
  adapterSha256:sha(path.join(out,'adapter.js')),
  catalogSha256:sha(path.join(out,'catalog.json')),
  formAliasesSha256:sha(aliasesPath),
  sources:Object.fromEntries([...modules.keys()].map(id=>[id+'.ts',sha(path.join(src,id+'.ts'))])),
  unmappedSpecies:missing.map(p=>({id:p.id,name:p.name,form:p.form,english:p.english,formEnglish:p.formEnglish})),
},null,2)+'\n');
console.log('Unmapped forms:',JSON.stringify(missing.map(p=>[p.id,p.english,p.formEnglish])));
